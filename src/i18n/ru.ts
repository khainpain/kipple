const pr = new Intl.PluralRules("ru");
/** plural(5, "карточка", "карточки", "карточек") → "карточек" */
function plural(n: number, one: string, few: string, many: string): string {
  const f = pr.select(n);
  return f === "one" ? one : f === "few" ? few : many;
}
